#!/usr/bin/env node

/**
 * Reproducible source/test/story inventory for the PBUI-AGENT-4 three-part review.
 *
 * Usage (from the pbui repository root):
 *   node ttmp/.../scripts/01-review-inventory.mjs \
 *     --output ttmp/.../various/11-review-inventory.md
 *
 * Generated code, dist trees, node_modules and Storybook build output are excluded.
 */

import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";

const root = process.cwd();
const args = process.argv.slice(2);
const outputIndex = args.indexOf("--output");
const output = outputIndex >= 0 ? resolve(root, args[outputIndex + 1]) : null;

const scopes = [
  { name: "PBUI core", roots: ["src"] },
  { name: "PBUI JS API and interaction", roots: ["packages/pbui-workbench/src", "packages/workbench-protocol/src"] },
  { name: "Agent framework and tiles", roots: ["packages/pbui-chat/src", "packages/pbui-chat/demo/src", "pkg/chatserver", "pkg/pbuichat"] },
];

const ignored = new Set(["node_modules", "dist", "storybook-static", ".git"]);
const sourceExtensions = new Set([".ts", ".tsx", ".go", ".css", ".proto"]);

function extension(path) {
  const match = path.match(/\.[^.\/]+$/);
  return match?.[0] ?? "";
}

function walk(start) {
  const absolute = resolve(root, start);
  const files = [];
  const visit = (path) => {
    const stat = statSync(path);
    if (stat.isDirectory()) {
      for (const entry of readdirSync(path)) {
        if (ignored.has(entry)) continue;
        visit(resolve(path, entry));
      }
      return;
    }
    files.push(relative(root, path));
  };
  visit(absolute);
  return files;
}

function lineCount(path) {
  const text = readFileSync(resolve(root, path), "utf8");
  return text === "" ? 0 : text.split(/\r?\n/).length;
}

function classify(path) {
  if (/\.test\.[jt]sx?$/.test(path) || /_test\.go$/.test(path)) return "test";
  if (/\.stories\.[jt]sx?$/.test(path)) return "story";
  if (path.includes("/generated/") || path.includes("/gen/")) return "generated";
  return "source";
}

function componentFolders(files) {
  const implementation = files.filter((path) => /\.(tsx)$/.test(path) && classify(path) === "source");
  const rows = [];
  for (const path of implementation) {
    const folder = dirname(path);
    const base = path.replace(/\.tsx$/, "");
    const hasTest = files.some((candidate) => candidate === `${base}.test.tsx` || (dirname(candidate) === folder && /\.test\.tsx$/.test(candidate)));
    const hasStory = files.some((candidate) => candidate === `${base}.stories.tsx` || (dirname(candidate) === folder && /\.stories\.tsx$/.test(candidate)));
    rows.push({ path, hasTest, hasStory });
  }
  return rows;
}

const lines = [
  "# PBUI-AGENT-4 review inventory",
  "",
  `Generated by \`${relative(root, import.meta.filename)}\` from commit \`${process.env.GIT_COMMIT ?? "(set GIT_COMMIT for provenance)"}\`.`,
  "",
  "> Counts are evidence for review scope, not quality scores. Generated files, dist, node_modules and Storybook output are excluded.",
  "",
];

for (const scope of scopes) {
  const files = [...new Set(scope.roots.flatMap(walk))].filter((path) => sourceExtensions.has(extension(path)));
  const buckets = { source: [], test: [], story: [], generated: [] };
  for (const file of files) buckets[classify(file)].push(file);
  const loc = Object.fromEntries(Object.entries(buckets).map(([key, values]) => [key, values.reduce((sum, path) => sum + lineCount(path), 0)]));
  const top = buckets.source
    .map((path) => ({ path, lines: lineCount(path) }))
    .sort((a, b) => b.lines - a.lines)
    .slice(0, 12);
  const components = componentFolders(files);

  lines.push(`## ${scope.name}`, "");
  lines.push(`- Production/source: **${buckets.source.length} files / ${loc.source} lines**.`);
  lines.push(`- Tests: **${buckets.test.length} files / ${loc.test} lines**.`);
  lines.push(`- Stories: **${buckets.story.length} files / ${loc.story} lines**.`);
  if (buckets.generated.length) lines.push(`- Generated: **${buckets.generated.length} files / ${loc.generated} lines** (excluded from source total).`);
  lines.push(`- TSX implementation files without a colocated/folder test: **${components.filter((item) => !item.hasTest).length} / ${components.length}**.`);
  lines.push(`- TSX implementation files without a colocated/folder story: **${components.filter((item) => !item.hasStory).length} / ${components.length}**.`);
  lines.push("", "### Largest production files", "");
  for (const item of top) lines.push(`- \`${item.path}\` — ${item.lines} lines`);
  lines.push("", "### TSX implementations without stories", "");
  const storyless = components.filter((item) => !item.hasStory).map((item) => item.path);
  if (storyless.length === 0) lines.push("- None.");
  else for (const path of storyless) lines.push(`- \`${path}\``);
  lines.push("");
}

const markdown = `${lines.join("\n")}\n`;
if (output) {
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, markdown);
  console.log(relative(root, output));
} else {
  process.stdout.write(markdown);
}
